/**
 * Returns effective permission list for a single role
 * @param {string} role
 * @returns {string[]}
 */
export function getPermissionsForRole(role) {
  const norm = normalizeRole(role);
  return ROLE_PERMISSIONS[norm] || [];
}

/**
 * Returns unified effective permission set for multiple roles
 * @param {string[]|string} roles
 * @param {string[]} [customPermissions=[]]
 * @returns {string[]}
 */
export function resolvePermissionsForUser(user) {
  if (!user) return [];
  if (user.role === ROLES.SUPER_ADMIN) return ALL_PERMISSIONS;

  const roles = Array.isArray(user.roles) ? user.roles : (user.role ? [user.role] : []);
  const permSet = new Set(user.customPermissions || []);

  for (const r of roles) {
    const rolePerms = getPermissionsForRole(r);
    for (const p of rolePerms) {
      permSet.add(p);
    }
  }

  return Array.from(permSet);
}
