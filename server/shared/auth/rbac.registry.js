/**
 * Normalizes role string (handling 'admin' as alias for 'school_admin')
 * @param {string} role
 * @returns {string}
 */
export function normalizeRole(role) {
  if (!role) return '';
  const clean = String(role).trim().toLowerCase();
  if (clean === ROLES.ADMIN) return ROLES.SCHOOL_ADMIN;
  return clean;
}

